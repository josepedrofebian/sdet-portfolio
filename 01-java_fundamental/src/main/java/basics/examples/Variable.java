package basics.examples;

// Mendefinisikan class dengan nama Variable
public class Variable {

    // Method main adalah titik awal program dijalankan
    public static void main(String[] args) {

        // Membuat variable bernama username
        // String digunakan untuk menyimpan data berupa teks
        String username = "jose";

        // Membuat variable bernama age
        // int digunakan untuk menyimpan bilangan bulat
        int age = 25;

        // Membuat variable bernama isLoggedIn
        // boolean digunakan untuk menyimpan nilai true atau false
        boolean isLoggedIn = true;

        // Menampilkan isi variable username ke console
        System.out.println(username);

        // Menampilkan isi variable age ke console
        System.out.println(age);

        // Menampilkan isi variable isLoggedIn ke console
        System.out.println(isLoggedIn);
    }
}