// Menentukan package tempat class DataType berada
package basics.examples;

// Mendefinisikan class dengan nama DataType
public class DataType {

    // Method main sebagai titik awal program
    public static void main(String[] args) {

        // Membuat variable bertipe int untuk menyimpan bilangan bulat
        int age = 26;

        // Membuat variable bertipe double untuk menyimpan angka desimal
        double testScore = 95.5;

        // Membuat variable bertipe boolean untuk menyimpan nilai true atau false
        boolean isLoggedIn = true;

        // Membuat variable bertipe char untuk menyimpan satu karakter
        char grade = 'A';

        // Membuat variable bertipe String untuk menyimpan teks
        String browser = "Chrome";

        // Menampilkan nilai age
        System.out.println(age);

        // Menampilkan nilai testScore
        System.out.println(testScore);

        // Menampilkan nilai isLoggedIn
        System.out.println(isLoggedIn);

        // Menampilkan nilai grade
        System.out.println(grade);

        // Menampilkan nilai browser
        System.out.println(browser);
    }
}