package basics.challenges;

// Buat sebuah class bernama VariableChallenge
public class VariableChallenge {

    // Buat method main sebagai titik awal program
    public static void main(String[] args) {

        // Buat variable bernama username
        // Gunakan tipe data String
        // Isi dengan username pilihan lu
        String username = "Jose Pedro Febian";

        // Buat variable bernama password
        // Gunakan tipe data String
        // Isi dengan password pilihan lu
        String password = "Rahasia";

        // Buat variable bernama age
        // Gunakan tipe data int
        // Isi dengan umur pilihan lu
        int age = 26;

        // Buat variable bernama isActive
        // Gunakan tipe data boolean
        // Isi dengan nilai true atau false
        boolean isActive = true;

        // Tampilkan username ke console
        System.out.println(username);

        // Tampilkan password ke console
        System.out.println(password);

        // Tampilkan age ke console
        System.out.println(age);

        // Tampilkan isActive ke console
        System.out.println(isActive);

        // Ubah nilai age menjadi nilai baru
        age = 28;

        // Tampilkan kembali age setelah nilainya diubah
        System.out.println(age);
    }

}